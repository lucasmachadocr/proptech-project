// Builds src/data/liveListings.ts from the public listings collected by hand:
//   scripts/data/spotahome-madrid-2026-11-12.txt   (id | €/month | neighbourhood | available from | bills)
//   scripts/data/madrid-neighbourhoods.json         (neighbourhood centre from OpenStreetMap Nominatim)
// Run: node scripts/build-live-listings.mjs
// Exact addresses are not public, so each flat sits near its neighbourhood centre (marked approxLocation).
import { readFileSync, writeFileSync } from 'node:fs';

const COLLECTED = '2026-11-12';
const hoods = JSON.parse(readFileSync('scripts/data/madrid-neighbourhoods.json', 'utf8'));
const MONTHS = ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'];
const title = (s) => s.replace(/\b\w/g, (c) => c.toUpperCase()).replace(/\bDe\b/g, 'de');

function fromDate(raw) {
  const [d, m, y] = raw.split(' ');
  const mo = MONTHS.indexOf(m) + 1;
  const year = y ? 2000 + Number(y) : mo >= 11 ? 2026 : 2027; // collected in Nov 2026
  const iso = `${year}-${String(mo).padStart(2, '0')}-${d.padStart(2, '0')}`;
  return iso < COLLECTED ? COLLECTED : iso;
}
const addYear = (iso) => `${Number(iso.slice(0, 4)) + 1}${iso.slice(4)}`;
/** Deterministic offset (±~250 m) so flats of one neighbourhood do not sit on one point. */
function jitter(id, k) {
  let h = 2166136261;
  for (const c of `${id}${k}`) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return (((h >>> 0) % 1000) / 1000 - 0.5) * 0.0045;
}

const rows = readFileSync('scripts/data/spotahome-madrid-2026-11-12.txt', 'utf8')
  .split('\n')
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((l) => l.split('|').map((x) => x.trim()));

const units = rows.map(([id, price, hood, from, bills]) => {
  const key = Object.keys(hoods).find((h) => h.toLowerCase() === hood.toLowerCase());
  const [lat, lng] = hoods[key];
  const zone = title(hood);
  const availableFrom = fromDate(from);
  return {
    id: `SAH-${id}`,
    providerId: 'SPOTAHOME',
    title: `1-bedroom flat in ${zone}`,
    type: '1bed',
    sqm: 0,
    rent: Number(price),
    zone,
    town: 'Madrid',
    city: 'Madrid',
    address: `${zone}, Madrid (neighbourhood)`,
    lat: +(lat + jitter(id, 'a')).toFixed(5),
    lng: +(lng + jitter(id, 'b') * 1.3).toFixed(5),
    amenities: [bills === 'all' ? 'Bills included' : bills === 'some' ? 'Some bills included' : 'Bills not included', 'Furnished'],
    availableFrom,
    availableTo: addYear(availableFrom),
    photos: [],
    ownerName: '',
    catastroOwner: '',
    listingCif: '',
    status: 'public',
    source: 'Spotahome',
    sourceUrl: `https://www.spotahome.com/madrid/for-rent:apartments/${id}`,
    approxLocation: true,
  };
});

const out = `// GENERATED by scripts/build-live-listings.mjs — do not edit by hand.
// ${units.length} real, publicly listed 1-bedroom furnished flats in Madrid (Spotahome search, collected ${COLLECTED}).
// Prices are the monthly prices shown on the listing; availability is not confirmed by Settle In.
// Locations are neighbourhood centres (OpenStreetMap Nominatim), not exact addresses.
import type { Unit } from '../types';

export const LIVE_LISTINGS_COLLECTED = '${COLLECTED}';
export const LIVE_UNITS: Unit[] = ${JSON.stringify(units, null, 1)};
`;
writeFileSync('src/data/liveListings.ts', out);
console.log(`src/data/liveListings.ts: ${units.length} listings`);
